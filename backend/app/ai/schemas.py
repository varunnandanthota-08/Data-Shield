from enum import Enum
from typing import Dict, List, Optional
from pydantic import BaseModel, Field


class RemediationActionType(str, Enum):
    REDACT_SENSITIVE_VALUES = "REDACT_SENSITIVE_VALUES"
    RESTRICT_PUBLIC_SHARING = "RESTRICT_PUBLIC_SHARING"
    LIMIT_AUTHORIZED_RECIPIENTS = "LIMIT_AUTHORIZED_RECIPIENTS"
    REQUEST_APPROVAL = "REQUEST_APPROVAL"
    REMOVE_UNNECESSARY_PERMISSIONS = "REMOVE_UNNECESSARY_PERMISSIONS"
    ROTATE_CREDENTIAL = "ROTATE_CREDENTIAL"
    REQUEST_HUMAN_REVIEW = "REQUEST_HUMAN_REVIEW"


class RemediationRecommendation(BaseModel):
    id: str = Field(description="Unique recommendation ID, e.g. REM-01")
    action_type: RemediationActionType = Field(description="Type of remediation action recommended")
    title: str = Field(description="Short action title")
    explanation: str = Field(description="Detailed explanation of the recommended action")
    reason: str = Field(description="Direct justification based on actual findings or triggered policies")
    expected_security_benefit: str = Field(description="Anticipated security or compliance outcome")
    requires_human_approval: bool = Field(default=False, description="Whether human approval is required before action")
    is_advisory: bool = Field(default=True, description="Always true; AI remediations are non-executing advisory guidance")


class AIContextAnalysisResult(BaseModel):
    incident_summary: str = Field(description="Short plain-language summary of the observed transfer incident")
    relevant_risk_factors: List[str] = Field(default_factory=list, description="Specific risk factors identified in this transfer context")
    policy_rationales: Dict[str, str] = Field(
        default_factory=dict,
        description="Plain-language explanation of triggered policy IDs (mapping policy ID -> rationale)",
    )
    ambiguities_and_uncertainty: List[str] = Field(
        default_factory=list,
        description="Identified ambiguities or missing contextual metadata",
    )
    remediation_recommendations: List[RemediationRecommendation] = Field(
        default_factory=list,
        description="Actionable least-privilege remediation recommendations",
    )
    human_review_recommended: bool = Field(default=False, description="Whether human review is recommended for this transfer")
    ai_status: str = Field(default="SUCCESS", description="AI status: SUCCESS, FALLBACK, or UNAVAILABLE")
    model_identifier: Optional[str] = Field(default=None, description="Model used or deterministic fallback indicator")
    is_ai_assisted: bool = Field(default=True, description="True if generated by AI; False if deterministic fallback")
    disclaimer: str = Field(
        default="AI-assisted explanations are advisory. Deterministic policies and risk scores remain authoritative.",
        description="Security boundary compliance disclaimer",
    )
